const { contextBridge, ipcRenderer, webUtils } = require('electron');

const invoke = (ch, ...args) => ipcRenderer.invoke(ch, ...args);

contextBridge.exposeInMainWorld('pc4', {
  getState: () => invoke('state:get'),
  updateSettings: patch => invoke('settings:update', patch),

  addGame: partial => invoke('game:add', partial),
  addGameFromPath: file => invoke('game:addFromPath', file),
  updateGame: (id, patch) => invoke('game:update', id, patch),
  removeGame: id => invoke('game:remove', id),
  launch: id => invoke('game:launch', id),
  closeGame: id => invoke('game:close', id),
  fetchMetadata: (id, opts) => invoke('game:fetchMetadata', id, opts),
  refreshAllMetadata: () => invoke('game:refreshAll'),
  setImage: (id, kind, src) => invoke('game:setImage', id, kind, src),
  openGameFolder: id => invoke('game:openFolder', id),
  setMusic: (id, file) => invoke('game:setMusic', id, file),
  findThemeSong: (id, manual) => invoke('game:findThemeSong', id, manual),
  findAllThemeSongs: () => invoke('game:findAllThemeSongs'),
  setThemeSongUrl: (id, url) => invoke('game:setThemeSongUrl', id, url),
  searchSongs: query => invoke('song:search', query),
  songStream: url => invoke('song:stream', url),
  clipboardText: () => invoke('app:clipboardText'),
  musicSearch: q => invoke('music:search', q),
  musicResolve: url => invoke('music:resolve', url),
  installSongFinder: () => invoke('themesong:install'),
  openMediaFolder: id => invoke('game:openMediaFolder', id),

  refreshNews: () => invoke('news:refresh'),
  getIndustry: () => invoke('industry:get'),
  refreshIndustry: () => invoke('industry:refresh'),
  readArticle: url => invoke('article:read', url),
  addPost: post => invoke('post:add', post),
  removePost: id => invoke('post:remove', id),
  steamScreenshots: appId => invoke('search:screenshots', appId),

  addFolder: (name, ids) => invoke('folder:add', name, ids),
  updateFolder: (id, patch) => invoke('folder:update', id, patch),
  removeFolder: id => invoke('folder:remove', id),

  importLibraries: sources => invoke('library:import', sources),
  searchSteam: term => invoke('search:steam', term),
  searchSgdb: term => invoke('search:sgdb', term),
  sgdbImages: (gameId, kind, page) => invoke('images:sgdb', gameId, kind, page),
  steamArtwork: appId => invoke('images:steamAll', appId),
  webImages: (name, kind, next) => invoke('images:web', name, kind, next),

  setAvatar: file => invoke('profile:setAvatar', file),
  openFile: opts => invoke('dialog:open', opts),
  setMode: m => invoke('app:setMode', m),
  window: action => invoke('app:window', action),
  power: action => invoke('app:power', action),
  openExternal: url => invoke('app:openExternal', url),
  version: () => invoke('app:version'),
  checkUpdate: () => invoke('app:checkUpdate'),
  installUpdate: () => invoke('app:installUpdate'),
  pathForFile: file => webUtils.getPathForFile(file),
  readSound: (name, style) => invoke('sound:read', name, style),
  openAssetFolder: which => invoke('app:openAssetFolder', which),
  requestController: () => invoke('hid:request'),
  openYouTube: () => invoke('youtube:open'),
  emuRumble: () => invoke('emu:rumble'),
  emuCheck: () => invoke('emu:check'),
  getVolume: () => invoke('volume:get'),
  setVolume: v => invoke('volume:set', v),
  audioOutputs: () => invoke('audio:outputs'),
  setAudioOutput: id => invoke('audio:outputs', id),
  backToGame: () => invoke('app:backToGame'),
  screenshot: () => invoke('capture:screenshot'),
  pauseGlobalKeys: on => invoke('keys:pause', on),
  warpStatus: () => invoke('warp:status'),
  warpConnect: () => invoke('warp:connect'),
  warpDisconnect: () => invoke('warp:disconnect'),
  warpInstall: () => invoke('warp:install'),
  toggleRecording: () => invoke('capture:record'),
  listCaptures: () => invoke('captures:list'),
  captureThumb: file => invoke('captures:thumb', file),
  deleteCapture: file => invoke('captures:delete', file),
  showCapture: file => invoke('captures:show', file),
  shop: force => invoke('shop:get', force),
  mediaRoots: () => invoke('media:roots'),
  mediaList: dir => invoke('media:list', dir),
  mediaThumb: file => invoke('media:thumb', file),
  mediaShow: file => invoke('media:show', file),
  mediaAddFolder: () => invoke('media:addFolder'),
  mediaRemoveFolder: p => invoke('media:removeFolder', p),
  emuRestart: () => invoke('emu:restart'),
  emuInstall: which => invoke('emu:install', which),
  closeYouTube: () => invoke('youtube:close'),
  clearYouTube: () => invoke('youtube:clear'),
  // the Quick Menu over a game (overlay window) and the music player it remote-controls
  overlayClose: backToGame => invoke('overlay:close', backToGame),
  overlayHandoff: action => invoke('overlay:handoff', action),
  playerCmd: (cmd, args) => invoke('player:cmd', cmd, args),
  playerState: snap => invoke('player:state', snap),

  on(channel, cb) {
    const allowed = ['state', 'task', 'game-started', 'game-stopped', 'game-failed', 'fullscreen-changed', 'youtube', 'quickmenu', 'go-home', 'pad-home', 'capture',
      'overlay-open', 'overlay-toggle', 'overlay-close', 'overlay-shown', 'overlay-nav', 'overlay-hint', 'qm-action', 'player-cmd', 'player-state', 'warp', 'update'];
    if (!allowed.includes(channel)) return () => {};
    const fn = (_e, ...args) => cb(...args);
    ipcRenderer.on(channel, fn);
    return () => ipcRenderer.removeListener(channel, fn);
  },
});
